#!/usr/bin/env bash
# Unified OpenAPI export for JA-EduSIS.
# Scramble → docs/api/console.openapi.json (Laravel route API)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BACKEND="${ROOT}/backend"
OUT="${ROOT}/docs/api"
mkdir -p "$OUT"

echo "==> Scramble export (console /api routes)"
(
  cd "$BACKEND"
  php artisan scramble:export --path="${OUT}/console.openapi.json"
)

# Index file for agents
cat >"${OUT}/INDEX.md" <<EOF
# OpenAPI export index

Generated by \`bash scripts/export-openapi.sh\` / \`npm run docs:openapi\`.

| Artifact | Source |
| :--- | :--- |
| \`console.openapi.json\` | Dedoc Scramble (\`php artisan scramble:export\`) |

Do not hand-edit JSON. Regenerate after API or model field changes.

Docs: [reference/http-api.md](../reference/http-api.md)
EOF

echo "OK  OpenAPI artifacts in ${OUT}"
ls -la "$OUT"
